package sqlimport

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/func-it/kanon/internal/names"
)

// A file is a file kan import writes, its path relative to the folder of the result.
type file struct {
	path string
	data []byte
}

// write gives the files of the result: the schema, the collection document, a document per row of an entity
// table and a file per file value.
func (m *model) write() []file {
	collection := schemaName(m.name)
	files := []file{
		{"schema.kanonarch", []byte(m.schema(collection))},
		{m.name + ".kan", []byte("---\ntype: " + collection + "\n---\n\n# " + names.Label(m.name) + "\n")},
	}
	for _, t := range m.tables {
		if t.kind != entity {
			continue
		}
		dir := m.name + "/" + t.field + "/"
		for i, id := range t.ids {
			doc, own := t.document(i)
			files = append(files, file{dir + id + ".kan", []byte(doc)})
			for _, f := range own {
				files = append(files, file{dir + f.path, f.data})
			}
		}
	}
	return files
}

// schema writes the schemas of the entity and weak tables in the order of their names, then the collection. Its
// header names no source, so that a database exported by kan sql imports back to the same schema.
func (m *model) schema(collection string) string {
	var b strings.Builder
	b.WriteString("// Generated by kan import.\n")
	var tables []*tbl
	var arrays []*field
	for _, t := range m.tables {
		switch t.kind {
		case entity:
			arrays = append(arrays, &field{name: t.field, typ: "[" + t.schema + "]", optional: len(t.ids) == 0})
			fallthrough
		case weak:
			tables = append(tables, t)
		}
	}
	slices.SortFunc(tables, func(a, b *tbl) int { return strings.Compare(a.schema, b.schema) })
	slices.SortFunc(arrays, func(a, b *field) int { return strings.Compare(a.name, b.name) })
	for _, t := range tables {
		writeSchema(&b, t.schema, t.fields, t.inverse)
	}
	writeSchema(&b, collection, arrays)
	return b.String()
}

// writeSchema writes a schema, each group of fields aligned and apart from the next.
func writeSchema(b *strings.Builder, name string, groups ...[]*field) {
	fmt.Fprintf(b, "\nschema %s {\n", name)
	first := true
	for _, g := range groups {
		if len(g) == 0 {
			continue
		}
		if !first {
			b.WriteString("\n")
		}
		first = false
		width := 0
		for _, f := range g {
			width = max(width, len(f.name)+1)
		}
		for _, f := range g {
			opt := ""
			if f.optional {
				opt = "?"
			}
			fmt.Fprintf(b, "  %-*s %s%s\n", width, f.name+":", f.typ, opt)
		}
	}
	b.WriteString("}\n")
}

// document writes the document of row i: its title, a key line per value, then a section per text of several
// lines, weak table and join table. It gives the files the document links to too.
func (t *tbl) document(i int) (string, []file) {
	id := t.ids[i]
	blocks := []string{"# " + names.Label(kebab(t.schema)) + " " + id}
	var keys, sections []string
	var files []file
	for _, f := range t.fields {
		section := func(body string) {
			if body != "" {
				sections = append(sections, "## "+names.Label(f.name)+"\n\n"+body)
			}
		}
		switch {
		case f.sub != nil && f.sub.kind == weak:
			section(f.sub.weakTable(id, t))
		case f.sub != nil:
			var items []string
			for j, p := range f.sub.parents {
				if p == id {
					items = append(items, "- [["+t.ref(f.sub.other.target, f.sub.links[f.sub.other][j])+"]]")
				}
			}
			section(strings.Join(items, "\n"))
		case f.fk == nil && t.types[f.col].native == "Prose":
			if s, ok := t.rows[i][f.col].(string); ok {
				section(prose(s))
			}
		default:
			v, ok := t.value(f, i, t)
			if !ok {
				continue
			}
			keys = append(keys, f.name+": "+v)
			if ct := t.types[f.col]; f.fk == nil && ct.exts != nil {
				files = append(files, file{id + "/" + f.name + "." + ct.exts[i], t.rows[i][f.col].([]byte)})
			}
		}
	}
	if len(keys) > 0 {
		blocks = append(blocks, strings.Join(keys, "\n"))
	}
	blocks = append(blocks, sections...)
	return strings.Join(blocks, "\n\n") + "\n", files
}

// weakTable writes the rows of a weak table whose parent is id, as a table in the document of doc.
func (t *tbl) weakTable(id string, doc *tbl) string {
	head := []string{"id"}
	for _, f := range t.fields {
		head = append(head, f.name)
	}
	lines := []string{row(head), "|" + strings.Repeat("---|", len(head))}
	for j, p := range t.parents {
		if p != id {
			continue
		}
		cells := []string{t.ids[j]}
		for _, f := range t.fields {
			v, _ := t.value(f, j, doc)
			cells = append(cells, strings.ReplaceAll(v, "|", `\|`))
		}
		lines = append(lines, row(cells))
	}
	if len(lines) == 2 {
		return ""
	}
	return strings.Join(lines, "\n")
}

func row(cells []string) string {
	var b strings.Builder
	b.WriteString("|")
	for _, c := range cells {
		if c != "" {
			b.WriteString(" " + c)
		}
		b.WriteString(" |")
	}
	return b.String()
}

// value writes the value of field f in row i, as it reads in the document of doc; false when there is none.
func (t *tbl) value(f *field, i int, doc *tbl) (string, bool) {
	if f.fk != nil {
		id := t.links[f.fk][i]
		return "[[" + doc.ref(f.fk.target, id) + "]]", id != ""
	}
	v := t.rows[i][f.col]
	if v == nil {
		return "", false
	}
	switch ct := t.types[f.col]; ct.native {
	case "Int", "Number":
		return number(v), true
	case "Bool":
		if v.(int64) == 1 {
			return "yes", true
		}
		return "no", true
	case "Date", "DateTime":
		return formatDate(v.(string), ct.native), true
	case "File", "Image":
		return "[[" + t.ids[i] + "/" + f.name + "." + ct.exts[i] + "]]", true
	}
	s := strings.TrimSpace(plain(v))
	return s, s != ""
}

// ref gives the link from a document of t to the object id of target: id in the same folder, else
// ../<folder>/<id>.
func (t *tbl) ref(target *tbl, id string) string {
	if target == t {
		return id
	}
	return "../" + target.field + "/" + id
}

var (
	keyLineRe = regexp.MustCompile(`^[\p{Ll}0-9][\p{L}0-9_-]*:(?:[ \t]|$)`)
	orderedRe = regexp.MustCompile(`^\d+[.)][ \t]`)
)

// prose writes a text of several lines so that it reads back the same: each line trimmed, one blank line
// between paragraphs, and a backslash before what Kanon or Markdown would read otherwise: \, { (an insertion), `
// (code), [ (a link), and a heading, table, list item, fence or key line at the start of a line.
func prose(s string) string {
	lines := layout(s)
	for i, l := range lines {
		if l != "" {
			lines[i] = escape(l)
		}
	}
	return strings.Join(lines, "\n")
}

// layout gives the lines of a text as a document holds them: each line trimmed, and one blank line between
// paragraphs.
func layout(s string) []string {
	var lines []string
	blank := false
	for _, l := range strings.Split(newlines.Replace(s), "\n") {
		l = strings.TrimSpace(l)
		if l == "" {
			blank = len(lines) > 0
			continue
		}
		if blank {
			lines = append(lines, "")
			blank = false
		}
		lines = append(lines, l)
	}
	return lines
}

func escape(l string) string {
	var b strings.Builder
	for i := 0; i < len(l); i++ {
		if c := l[i]; c == '\\' || c == '{' || c == '`' || c == '[' {
			b.WriteByte('\\')
		}
		b.WriteByte(l[i])
	}
	s := b.String()
	switch {
	case strings.HasPrefix(s, "#"), strings.HasPrefix(s, "|"), strings.HasPrefix(s, "~~~"),
		len(s) > 1 && strings.ContainsRune("-*+", rune(s[0])) && (s[1] == ' ' || s[1] == '\t'):
		return `\` + s
	case orderedRe.MatchString(s):
		i := strings.IndexAny(s, ".)")
		return s[:i] + `\` + s[i:]
	case keyLineRe.MatchString(s):
		i := strings.IndexByte(s, ':')
		return s[:i] + `\` + s[i:]
	}
	return s
}
